//! 界面配色里**需要跨文件保持一致**的那几个值。
//!
//! 只收「选中态的底色」这一类:它们散在表单、节点表、用户表里,各写一遍
//! 魔法值的话,改一次要翻三个文件,而漏改的表现是「有的地方选中框跟别处不一样」——
//! 一眼看不出是 bug,只觉得界面不整齐。
//!
//! 其余颜色(状态绿/红、标签黄)就地写着,它们各自只用在一处。

use ratatui::style::Color;

/// 表单里**聚焦那一格**的底色。
///
/// **不用亮色做底。** 早先这里是 `fg(Black).bg(Cyan)` —— 亮青底配黑字,
/// 而前景色在很多终端配色下会被主题改掉,结果是亮底浅字,
/// 对比度反而比不选中还低,字都看不清了。
///
/// 深灰蓝底 + 原色前景在任何配色下都是「亮一块」,
/// 不依赖终端把 `Color::Black` 渲染成真的黑。
pub const SELECT_BG: Color = Color::Rgb(0x2d, 0x3a, 0x4e);

/// 表格里**选中行**的底色。比 `SELECT_BG` 淡一点 ——
/// 那是「光标在这一行」,不是「正在编辑这一格」,两者不该一样强。
///
/// 比 `Color::DarkGray` 暗:后者在多数终端上是「亮黑」(≈ #555),
/// 压着整行文字读起来发灰。
pub const ROW_BG: Color = Color::Rgb(0x2a, 0x2a, 0x2a);
